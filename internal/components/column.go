// MJColumnComponent represents mj-column
// Columns enable you to horizontally organize the content within your sections.
// They must be located under mj-section tags in order to be considered by the engine.
// To be responsive, columns are expressed in terms of percentage.
// The sum of columns in a section cannot be greater than the width of the parent `mj-section` (or 100%).
// Every single column has to contain something because they are responsive containers, and will be vertically stacked on a mobile view.
// Any standard component, or component that you have defined and registered, can be placed within a column – except mj-column or mj-section elements.
type MJColumnComponent struct {
	*BaseComponent
}

// NewMJColumnComponent creates a new mj-column component
func NewMJColumnComponent(node *parser.MJMLNode, opts *options.RenderOpts) *MJColumnComponent {
	return &MJColumnComponent{
		BaseComponent: NewBaseComponent(node, opts),
	}
}

func (c *MJColumnComponent) GetTagName() string {
	return "mj-column"
}

// contentWidth returns the width the column gives its children, as
// mjml-column's getChildContext computes it: the column's width in its
// container (childBaseWidth), minus its left and right padding, borders and
// inner borders; its children read it like parseInt.
// AIDEV-NOTE: width-flow-core; the content width the column gives its children (childContext)
func (c *MJColumnComponent) contentWidth() float64 {
	boxSides := sumLengths(c.shorthandAttrValue(c, constants.MJMLPadding, sideLeft),
		c.shorthandAttrValue(c, constants.MJMLPadding, sideRight),
		c.shorthandBorderValue(c, constants.MJMLBorder, sideLeft),
		c.shorthandBorderValue(c, constants.MJMLBorder, sideRight),
		c.shorthandBorderValue(c, constants.MJMLInnerBorder, sideLeft),
		c.shorthandBorderValue(c, constants.MJMLInnerBorder, sideRight))
	return max(c.childBaseWidth(c)-float64(boxSides), 0)
}

// exactWidth returns the column's width in its container with its fraction,
// as mjml-column's getWidthAsPixel computes it (parseFloat of the container
// width).
func (c *MJColumnComponent) exactWidth() float64 {
	return widthIn(c.GetParsedWidth(), c.BaseComponent.layoutWidth())
}

// Render implements optimized Writer-based rendering for MJColumnComponent
func (c *MJColumnComponent) Render(w io.StringWriter) error {
	// Cache attribute lookups to avoid repeated calls
	verticalAlign := c.resolveAttribute(c, constants.MJMLVerticalAlign)
	direction := c.resolveAttribute(c, constants.MJMLDirection)

	// Get column class and mobile width following mjml-column
	className, _ := c.GetColumnClass()
	mobileWidth := c.mobileWidth()

	// Column div with MJML responsive styles matching exact property order
	// NOTE: MSO conditional TD is generated by the parent section component
	columnDiv := html.NewHTMLTag("div")
	c.addDebugAttribute(columnDiv, "column")

	// MJML writes getColumnClass(), the gutter class (MJML 5.4), then
	// 'mj-outlook-group-fix' and css-class.
	if c.hasColumnGutter() {
		c.setClassAttribute(columnDiv, className, c.gutterClassName(), "mj-outlook-group-fix")
	} else {
		c.setClassAttribute(columnDiv, className, "mj-outlook-group-fix")
	}

	// Always apply full column styles (same for all contexts)
	columnDiv.
		AddStyle(constants.CSSFontSize, "0px").
		AddStyle(constants.CSSTextAlign, "left").
		AddStyle(constants.CSSDirection, direction).
		AddStyle(constants.CSSDisplay, "inline-block").
		AddStyle(constants.CSSVerticalAlign, verticalAlign).
		AddStyle(constants.CSSWidth, mobileWidth)
	if c.hasColumnGutter() {
		columnDiv.AddStyle(constants.CSSPadding, c.mobileGutterCSS())
	}

	if err := columnDiv.RenderOpen(w); err != nil {
		return err
	}

	// Check if we need gutter table for padding (following MJML JS pattern)
	if c.hasGutter() {
		if err := c.renderGutter(w); err != nil {
			return err
		}
	} else {
		if err := c.renderColumnToWriter(w); err != nil {
			return err
		}
	}

	if err := columnDiv.RenderClose(w); err != nil {
		return err
	}

	return nil
}

// renderColumnToWriter renders the column content directly to Writer
func (c *MJColumnComponent) renderColumnToWriter(w io.StringWriter) error {
	return c.renderColumnWithStylesToWriter(w, true)
}

// renderColumnWithStylesToWriter creates the inner column table with optional styles and writes to Writer
func (c *MJColumnComponent) renderColumnWithStylesToWriter(w io.StringWriter, includeStyles bool) error {
	// Inner table for column content
	innerTable := html.NewTableTag().AddAttribute("width", "100%")

	// Support inner background/border attributes following mjml-column.
	innerBg := c.resolveAttribute(c, constants.MJMLInnerBackgroundColor)
	innerBR := c.resolveAttribute(c, constants.MJMLInnerBorderRadius)

	if includeStyles {
		// Without a gutter, the inner table takes the column's own table
		// style (mjml-column's tableStyle): its background, borders and border
		// radius; the inner-* attributes apply only to a column with a gutter,
		// except that an inner border radius separates the borders.
		c.addTableStyle(innerTable)
		if innerBR != "" && c.resolveAttribute(c, constants.MJMLBorderRadius) == "" {
			innerTable.AddStyle(constants.CSSBorderCollapse, constants.BorderCollapseSeparate)
		}
	} else {
		// Gutter path: the inner table takes mjml-column's table style for a
		// column with a gutter, in its order: the inner background and inner
		// borders.
		if innerBg != "" {
			innerTable.AddStyle(constants.CSSBackgroundColor, innerBg)
		}
		for _, side := range []struct{ attr, css string }{
			{constants.MJMLInnerBorder, constants.CSSBorder},
			{constants.MJMLInnerBorder + "-bottom", constants.CSSBorderBottom},
			{constants.MJMLInnerBorder + "-left", constants.CSSBorderLeft},
			{constants.MJMLInnerBorderRadius, constants.CSSBorderRadius},
			{constants.MJMLInnerBorder + "-right", constants.CSSBorderRight},
			{constants.MJMLInnerBorder + "-top", constants.CSSBorderTop},
		} {
			if value := c.resolveAttribute(c, side.attr); value != "" {
				innerTable.AddStyle(side.css, value)
			}
		}
		if innerBR != "" {
			innerTable.AddStyle(constants.CSSBorderCollapse, constants.BorderCollapseSeparate)
		}
	}

	if err := innerTable.RenderOpen(w); err != nil {
		return err
	}
	if _, err := w.WriteString("<tbody>"); err != nil {
		return err
	}

	// The children, each in the row and cell renderColumn gives it; their
	// width is in their context (childContext).
	for _, child := range c.children {
		if err := renderInCell(w, child, false); err != nil {
			return err
		}
	}

	if _, err := w.WriteString("</tbody>"); err != nil {
		return err
	}
	if err := innerTable.RenderClose(w); err != nil {
		return err
	}

	return nil
}

func (c *MJColumnComponent) GetDefaultAttribute(name string) string {
	switch name {
	case "vertical-align":
		return "top"
	case "direction":
		return "ltr"
	case "text-align":
		return "left"
	default:
		return ""
	}
}

// GetParsedWidth returns the parsed width following mjml-column
func (c *MJColumnComponent) GetParsedWidth() styles.Size {
	// The width attribute, mj-class and mj-attributes included, as MJML's
	// getAttribute reads it, through mjml-core's widthParser: pixels with
	// parseInt (200.9px is 200px), and any unit but "%" as pixels.
	if width, ok := c.parsedWidthAttribute(); ok {
		return width.size
	}
	// Default: auto-calculate percentage based on siblings
	nonRawSiblings := c.getNonRawSiblings()
	if nonRawSiblings <= 0 {
		nonRawSiblings = 1
	}
	widthPercent := 100.0 / float64(nonRawSiblings)
	return styles.NewPercentSize(widthPercent)
}

// parsedWidthAttribute returns the column's width attribute as mjml-core's
// widthParser reads it, or false when no layer sets one or it holds no
// number.
func (c *MJColumnComponent) parsedWidthAttribute() (mjmlWidth, bool) {
	widthAttr := c.resolveAttribute(c, constants.MJMLWidth)
	if widthAttr == "" {
		return mjmlWidth{}, false
	}
	return parseMJMLWidth(widthAttr)
}

// GetColumnClass returns the column's responsive class and the width of its
// media-query rule, as mjml-column's getColumnClass and mjml-core's
// addMediaQuery write them: mj-column-per-N for a "%" width (the first dot
// a dash), mj-column-px-N for any other unit, and the rule's width with the
// unit as written (300PX).
func (c *MJColumnComponent) GetColumnClass() (string, string) {
	if c.hasColumnGutter() {
		// The width less the column's share of the gutters (getDesktopWidth),
		// rounded in pixels; the number as JavaScript writes it.
		width, unit := c.desktopWidth()
		if unit == "px" {
			width = jsMathRound(width)
		}
		number := strings.Replace(jsNumber(width), ".", "-", 1)
		if unit == "%" {
			return "mj-column-per-" + number, jsNumber(width) + unit
		}
		return "mj-column-px-" + number, jsNumber(width) + unit
	}
	width, ok := c.parsedWidthAttribute()
	if !ok {
		width = mjmlWidth{size: c.GetParsedWidth(), unit: "%"}
	}
	number := strings.Replace(jsNumber(width.size.Value()), ".", "-", 1)
	if width.size.IsPercent() {
		return "mj-column-per-" + number, width.cssText()
	}
	return "mj-column-px-" + number, width.cssText()
}

// GetWidthAsPixel converts the parsed width to pixels for MSO compatibility
// Following mjml-column's getWidthAsPixel
func (c *MJColumnComponent) GetWidthAsPixel() string {
	// Rounded to a whole pixel with Math.round, as mjml-column's
	// normalizePxValue does since MJML 5 (199.98px is 200px). The container
	// width is never negative (SetContext), and 0 when a box's padding leaves
	// no room: the column is then 0px wide, not 100%.
	return jsPixels(jsMathRound(c.exactWidth()))
}

// mobileWidth returns the width of the column's div, its width on mobile,
// as mjml-column's getMobileWidth writes it: 100% outside a group; in a
// group, where MJML passes mobileWidth, an equal share truncated like
// parseInt for a column without width, a percentage width as written, and a
// pixel width as a share of the group.
func (c *MJColumnComponent) mobileWidth() string {
	if !c.Context().InsideGroup {
		return "100%"
	}
	// A group's columns do not stack: with a gutter, they keep their
	// desktop width less the gutters, as a percentage of the group.
	if c.hasColumnGutter() {
		width, unit := c.desktopWidth()
		if unit == "%" {
			return jsNumber(width) + "%"
		}
		containerWidth := math.Trunc(c.BaseComponent.layoutWidth())
		if containerWidth == 0 {
			return "100%" // MJML would divide by zero
		}
		return jsNumber(jsToFixed6(width/containerWidth*100)) + "%"
	}
	width := c.resolveAttribute(c, constants.MJMLWidth)
	if width == "" {
		nonRawSiblings := max(c.getNonRawSiblings(), 1)
		return strconv.Itoa(100/nonRawSiblings) + "%"
	}
	// A "%" width as written; any other unit is pixels ("50 %", "40%;").
	parsed, ok := parseMJMLWidth(width)
	if ok && parsed.size.IsPercent() {
		return width
	}
	// parsedWidth / parseInt(containerWidth, 10) * 100, on the group's
	// width as a float, which a 999999999999px group keeps whole.
	containerWidth := math.Trunc(c.BaseComponent.layoutWidth())
	if containerWidth == 0 {
		return "100%" // MJML would divide by zero
	}
	pixels := 0.0 // a width with no number, NaN in MJML
	if ok {
		pixels = parsed.size.Value()
	}
	// Cut to 6 decimals, as normalizeUnitValue does since MJML 5.
	return jsNumber(jsToFixed6(pixels/containerWidth*100)) + "%"
}

// GetEffectiveWidth overrides BaseComponent to return the column's calculated pixel width
// instead of the inherited container width. This ensures child components get the correct width.
func (c *MJColumnComponent) GetEffectiveWidth() int {
	// A container width of 0 is a real width (a box with no room left): a
	// percentage of it is 0, a pixel width stays as written, as in MJML.
	return lengthFromFloat(c.exactWidth())
}

// GetMSOTDStyles returns the styles that should be applied to the MSO conditional TD
// This is called by the parent section component, matching mjml-column's tdOutlook style
func (c *MJColumnComponent) GetMSOTDStyles() map[string]string {
	getAttr := func(name string) string {
		if attr := c.getAttribute(name); attr != nil {
			return *attr
		}
		return c.GetDefaultAttribute(name)
	}

	verticalAlign := getAttr("vertical-align")

	// Calculate pixel width for MSO conditional as mjml-column computes it
	msoPixelWidth := c.GetWidthAsPixel()

	return map[string]string{
		"vertical-align": verticalAlign,
		"width":          msoPixelWidth,
	}
}

// hasGutter checks if the column has any padding attributes
func (c *MJColumnComponent) hasGutter() bool {
	// As mjml-column's hasGutter: a padding attribute that is set, even to the
	// empty string, gives the column a gutter.
	for _, attr := range []string{constants.MJMLPadding, constants.MJMLPaddingTop, constants.MJMLPaddingRight, constants.MJMLPaddingBottom, constants.MJMLPaddingLeft} {
		if c.hasAttribute(c, attr) {
			return true
		}
	}
	return false
}

// renderGutter creates the gutter table wrapper when padding is present
func (c *MJColumnComponent) renderGutter(w io.StringWriter) error {
	hasBorderRadius := c.resolveAttribute(c, constants.MJMLBorderRadius) != ""

	// Outer gutter table
	gutterTable := html.NewTableTag().AddAttribute("width", "100%")
	if hasBorderRadius {
		gutterTable.AddStyle(constants.CSSBorderCollapse, constants.BorderCollapseSeparate)
	}
	if err := gutterTable.RenderOpen(w); err != nil {
		return err
	}
	if _, err := w.WriteString("<tbody><tr>"); err != nil {
		return err
	}

	// TD with padding styles (this is where the padding gets applied)
	gutterTd := html.NewHTMLTag("td")
	c.addTableStyle(gutterTd)

	// Apply padding attributes to the gutter TD
	if padding := c.resolveAttribute(c, constants.MJMLPadding); padding != "" {
		gutterTd.AddStyle(constants.CSSPadding, padding)
	}
	if paddingTop := c.resolveAttribute(c, constants.MJMLPaddingTop); paddingTop != "" {
		gutterTd.AddStyle(constants.CSSPaddingTop, paddingTop)
	}
	if paddingRight := c.resolveAttribute(c, constants.MJMLPaddingRight); paddingRight != "" {
		gutterTd.AddStyle(constants.CSSPaddingRight, paddingRight)
	}
	if paddingBottom := c.resolveAttribute(c, constants.MJMLPaddingBottom); paddingBottom != "" {
		gutterTd.AddStyle(constants.CSSPaddingBottom, paddingBottom)
	}
	if paddingLeft := c.resolveAttribute(c, constants.MJMLPaddingLeft); paddingLeft != "" {
		gutterTd.AddStyle(constants.CSSPaddingLeft, paddingLeft)
	}

	if err := gutterTd.RenderOpen(w); err != nil {
		return err
	}

	// Inner column table (without styles since gutter TD handles them)
	if err := c.renderColumnWithStylesToWriter(w, false); err != nil {
		return err
	}

	if err := gutterTd.RenderClose(w); err != nil {
		return err
	}
	if _, err := w.WriteString("</tr></tbody>"); err != nil {
		return err
	}
	return gutterTable.RenderClose(w)
}

// addTableStyle writes mjml-column's tableStyle, in its order: the
// background color, the border and its sides around the border radius,
// the vertical alignment, and a separate border model when the column has a
// border radius. The inner table of a column without gutter and the gutter
// cell of a column with one take it.
func (c *MJColumnComponent) addTableStyle(tag *html.HTMLTag) {
	for _, style := range []struct{ attr, css string }{
		{constants.MJMLBackgroundColor, constants.CSSBackgroundColor},
		{constants.MJMLBorder, constants.CSSBorder},
		{constants.MJMLBorderBottom, constants.CSSBorderBottom},
		{constants.MJMLBorderLeft, constants.CSSBorderLeft},
		{constants.MJMLBorderRadius, constants.CSSBorderRadius},
		{constants.MJMLBorderRight, constants.CSSBorderRight},
		{constants.MJMLBorderTop, constants.CSSBorderTop},
		{constants.MJMLVerticalAlign, constants.CSSVerticalAlign},
	} {
		// Written when set, even to "" (vertical-align:;), as mjml-core
		// leaves out only the styles whose attribute is unset.
		if c.hasAttribute(c, style.attr) {
			tag.AddStyle(style.css, c.resolveAttribute(c, style.attr))
		}
	}
	if c.resolveAttribute(c, constants.MJMLBorderRadius) != "" {
		tag.AddStyle(constants.CSSBorderCollapse, constants.BorderCollapseSeparate)
	}
}

// renderInCell writes a child as mjml-column's renderColumn does, and
// mjml-hero's render with backgroundAttr: a raw child as it is, any other in
// a row and a cell built from its own attributes (align, css-class,
// container-background-color, padding and its sides), whatever the child.
func renderInCell(w io.StringWriter, child Component, backgroundAttr bool) error {
	if child.IsRawElement() {
		return child.Render(w)
	}
	td := html.NewHTMLTag("td")
	if align, set := attributeOf(child, constants.MJMLAlign); set {
		td.AddAttribute(constants.AttrAlign, align)
	}
	background, backgroundSet := attributeOf(child, constants.MJMLContainerBackgroundColor)
	if backgroundAttr && backgroundSet {
		td.AddAttribute(constants.AttrBackground, background)
	}
	// No empty class: MJML's minifier drops it.
	if css, _ := attributeOf(child, constants.MJMLCSSClass); css != "" {
		td.AddAttribute(constants.AttrClass, css)
	}
	var own []html.StyleProperty
	if backgroundSet {
		own = append(own, html.StyleProperty{Name: constants.CSSBackground, Value: background})
	}
	own = append(own, html.StyleProperty{Name: constants.CSSFontSize, Value: "0px"})
	for _, side := range []struct{ attr, css string }{
		{constants.MJMLPadding, constants.CSSPadding},
		{constants.MJMLPaddingTop, constants.CSSPaddingTop},
		{constants.MJMLPaddingRight, constants.CSSPaddingRight},
		{constants.MJMLPaddingBottom, constants.CSSPaddingBottom},
		{constants.MJMLPaddingLeft, constants.CSSPaddingLeft},
	} {
		if value, set := attributeOf(child, side.attr); set {
			own = append(own, html.StyleProperty{Name: side.css, Value: value})
		}
	}
	own = append(own, html.StyleProperty{Name: constants.CSSWordBreak, Value: "break-word"})
	for _, style := range own {
		td.AddStyle(style.Name, style.Value)
	}
	if _, err := w.WriteString("<tr>"); err != nil {
		return err
	}
	if err := td.RenderOpen(w); err != nil {
		return err
	}
	if err := child.Render(w); err != nil {
		return err
	}
	_, err := w.WriteString("</td></tr>")
	return err
}
