// MJCarouselComponent represents the mj-carousel component
type MJCarouselComponent struct {
	*BaseComponent
	id string // generated by generateCarouselID, once per carousel
}

func NewMJCarouselComponent(node *parser.MJMLNode, opts *options.RenderOpts) *MJCarouselComponent {
	return &MJCarouselComponent{
		BaseComponent: NewBaseComponent(node, opts),
	}
}

func (c *MJCarouselComponent) Render(w io.StringWriter) error {
	// Generate unique carousel ID
	carouselID := c.generateCarouselID()

	// Get carousel images from children
	// An mj-carousel without images renders too, as in MJML.
	carouselImages := c.getCarouselImages()

	// Render main carousel content
	if err := c.renderCarouselContent(w, carouselID, carouselImages); err != nil {
		return err
	}

	// Render MSO fallback
	if err := c.renderMSOFallback(w, carouselImages); err != nil {
		return err
	}

	return nil
}

func (c *MJCarouselComponent) GetTagName() string {
	return "mj-carousel"
}

// GenerateCSS generates the CSS for this carousel component
func (c *MJCarouselComponent) GenerateCSS() string {
	// Generate unique carousel ID
	carouselID := c.generateCarouselID()

	// As mjml-carousel's componentHeadStyle, over props.children: every
	// child element, an unknown tag included, even with no image.
	count := c.childCount()
	if count == 0 {
		return ""
	}

	return c.buildCarouselCSS(carouselID, count)
}

// childCount is the length of mjml-carousel's props.children: the child
// elements of the tag, unknown tags included, which its CSS and its
// previous and next labels run over.
func (c *MJCarouselComponent) childCount() int {
	return len(c.Node.Children)
}

// imageNumber is the number mjml-carousel-image writes for img: its
// props.index plus 1, its position among all the carousel's children.
func imageNumber(img *MJCarouselImageComponent) int {
	return img.ctx.index + 1
}

func (c *MJCarouselComponent) GetDefaultAttribute(name string) string {
	// TODO: Consider more performant approaches to attribute matching than switch statements,
	// such as static map[string]string lookups or compile-time generated code for components
	// with many default attributes (10+ attributes). Switch statements may have O(n) lookup
	// time while map lookups are O(1) average case.
	switch name {
	case "align":
		return "center"
	case "border-radius":
		return "6px"
	case "icon-width":
		return "44px"
	case "left-icon":
		return "https://i.imgur.com/xTh3hln.png"
	case "right-icon":
		return "https://i.imgur.com/os7o9kz.png"
	case "tb-border":
		return "2px solid transparent"
	case "tb-border-radius":
		return "6px"
	case "tb-hover-border-color":
		return "#fead0d"
	case "tb-selected-border-color":
		return "#cccccc"
	case "thumbnails":
		return "visible"
	default:
		return ""
	}
}

// MJCarouselImageComponent represents the mj-carousel-image component
type MJCarouselImageComponent struct {
	*BaseComponent
}

func NewMJCarouselImageComponent(node *parser.MJMLNode, opts *options.RenderOpts) *MJCarouselImageComponent {
	return &MJCarouselImageComponent{
		BaseComponent: NewBaseComponent(node, opts),
	}
}

// Render writes an mj-carousel-image outside any mj-carousel (misplaced,
// rendered by the soft validation), as mjml-carousel-image's render does
// there: its image in its div, numbered by its position among its parent's
// children, at the width its parent gives it. Inside an mj-carousel, the
// carousel renders its images.
func (c *MJCarouselImageComponent) Render(w io.StringWriter) error {
	return renderCarouselImage(w, c, c.ctx.index+1, false, jsPixels(c.layoutWidth()), c.GetEffectiveWidth())
}

func (c *MJCarouselImageComponent) GetTagName() string {
	return "mj-carousel-image"
}

func (c *MJCarouselImageComponent) GetDefaultAttribute(name string) string {
	switch name {
	case "target":
		return "_blank"
	default:
		return ""
	}
}

// buildCarouselCSS builds the carousel CSS content as a string
func (c *MJCarouselComponent) buildCarouselCSS(carouselID string, imageCount int) string {
	iconWidth := c.resolveAttribute(c, constants.MJMLIconWidth)
	tbHoverBorderColor := c.resolveAttribute(c, constants.MJMLTBHoverBorderColor)
	tbSelectedBorderColor := c.resolveAttribute(c, constants.MJMLTBSelectedBorderColor)

	var css strings.Builder

	repeat := func(count int) string {
		if count <= 0 {
			return ""
		}
		return strings.Repeat("+ * ", count)
	}

	writeSelectorBlock := func(selectors []string, joiner, body string) {
		if len(selectors) == 0 {
			return
		}

		css.WriteString("    ")
		css.WriteString(strings.Join(selectors, joiner))
		css.WriteString(" {\n")
		css.WriteString(body)
		css.WriteString("\n    }\n\n")
	}

	css.WriteString(".mj-carousel {\n")
	css.WriteString("      -webkit-user-select: none;\n")
	css.WriteString("      -moz-user-select: none;\n")
	css.WriteString("      user-select: none;\n")
	css.WriteString("    }\n\n")

	writeSelectorBlock(
		[]string{fmt.Sprintf(".mj-carousel-%s-icons-cell", carouselID)},
		",\n    ",
		fmt.Sprintf("      display: table-cell !important;\n      width: %s !important;", iconWidth),
	)

	css.WriteString("    .mj-carousel-radio,\n")
	css.WriteString("    .mj-carousel-next,\n")
	css.WriteString("    .mj-carousel-previous {\n")
	css.WriteString("      display: none !important;\n")
	css.WriteString("    }\n\n")

	css.WriteString("    .mj-carousel-thumbnail,\n")
	css.WriteString("    .mj-carousel-next,\n")
	css.WriteString("    .mj-carousel-previous {\n")
	css.WriteString("      touch-action: manipulation;\n")
	css.WriteString("    }\n\n")

	hideSelectors := make([]string, imageCount)
	for i := range imageCount {
		hideSelectors[i] = fmt.Sprintf(
			".mj-carousel-%s-radio:checked %s+ .mj-carousel-content .mj-carousel-image",
			carouselID,
			repeat(i),
		)
	}
	writeSelectorBlock(hideSelectors, ",", "      display: none !important;")

	showSelectors := make([]string, imageCount)
	for i := range imageCount {
		showSelectors[i] = fmt.Sprintf(
			".mj-carousel-%s-radio-%d:checked %s+ .mj-carousel-content .mj-carousel-image-%d",
			carouselID,
			i+1,
			repeat(imageCount-i-1),
			i+1,
		)
	}
	writeSelectorBlock(showSelectors, ",", "      display: block !important;")

	nextSelectors := make([]string, imageCount)
	previousSelectors := make([]string, imageCount)
	for i := range imageCount {
		padding := repeat(imageCount - i - 1)

		nextSelectors[i] = fmt.Sprintf(
			".mj-carousel-%s-radio-%d:checked %s+ .mj-carousel-content .mj-carousel-next-%d",
			carouselID,
			i+1,
			padding,
			(i+1)%imageCount+1,
		)
		previousSelectors[i] = fmt.Sprintf(
			".mj-carousel-%s-radio-%d:checked %s+ .mj-carousel-content .mj-carousel-previous-%d",
			carouselID,
			i+1,
			padding,
			(i-1+imageCount)%imageCount+1,
		)
	}

	css.WriteString("    .mj-carousel-previous-icons,\n")
	css.WriteString("    .mj-carousel-next-icons,\n")
	css.WriteString("    ")
	css.WriteString(strings.Join(nextSelectors, ","))
	css.WriteString(",\n")
	css.WriteString("    ")
	css.WriteString(strings.Join(previousSelectors, ","))
	css.WriteString(" {\n")
	css.WriteString("      display: block !important;\n")
	css.WriteString("    }\n\n")

	thumbSelectors := make([]string, imageCount)
	for i := range imageCount {
		thumbSelectors[i] = fmt.Sprintf(
			".mj-carousel-%s-radio-%d:checked %s+ .mj-carousel-content .mj-carousel-%s-thumbnail-%d",
			carouselID,
			i+1,
			repeat(imageCount-i-1),
			carouselID,
			i+1,
		)
	}
	writeSelectorBlock(
		thumbSelectors,
		",",
		fmt.Sprintf("      border-color: %s !important;", tbSelectedBorderColor),
	)

	// MJML 5.4.1 shows the thumbnails only once a radio is checked. Its template
	// leaves a newline and indentation after each selector, kept here so the
	// output matches byte for byte.
	thumbDisplaySelectors := make([]string, imageCount)
	for i := range imageCount {
		thumbDisplaySelectors[i] = fmt.Sprintf(
			".mj-carousel-%s-radio-%d:checked %s+ .mj-carousel-content .mj-carousel-%s-thumbnail\n          ",
			carouselID,
			i+1,
			repeat(imageCount-i-1),
			carouselID,
		)
	}
	writeSelectorBlock(
		thumbDisplaySelectors,
		",",
		"      display: inline-block !important;",
	)

	writeSelectorBlock(
		[]string{".mj-carousel-image img + div", ".mj-carousel-thumbnail img + div"},
		",\n    ",
		"      display: none !important;",
	)

	hoverSelectors := make([]string, 0, imageCount)
	for i := imageCount - 1; i >= 0; i-- {
		hoverSelectors = append(hoverSelectors, fmt.Sprintf(
			".mj-carousel-%s-thumbnail:hover %s+ .mj-carousel-main .mj-carousel-image",
			carouselID,
			repeat(i),
		))
	}
	writeSelectorBlock(hoverSelectors, ",", "      display: none !important;")

	css.WriteString(fmt.Sprintf("    .mj-carousel-thumbnail:hover {\n      border-color: %s !important;\n    }\n\n", tbHoverBorderColor))

	showThumbSelectors := make([]string, imageCount)
	for i := range imageCount {
		showThumbSelectors[i] = fmt.Sprintf(
			".mj-carousel-%s-thumbnail-%d:hover %s+ .mj-carousel-main .mj-carousel-image-%d",
			carouselID,
			i+1,
			repeat(imageCount-i-1),
			i+1,
		)
	}
	css.WriteString("    ")
	css.WriteString(strings.Join(showThumbSelectors, ","))
	css.WriteString(" {\n")
	css.WriteString("      display: block !important;\n")
	css.WriteString("    }\n")
	css.WriteString("    \n\n")

	css.WriteString("      .mj-carousel noinput { display:block !important; }\n")
	css.WriteString("      .mj-carousel noinput .mj-carousel-image-1 { display: block !important;  }\n")
	css.WriteString("      .mj-carousel noinput .mj-carousel-arrows,\n")
	css.WriteString("      .mj-carousel noinput .mj-carousel-thumbnails { display: none !important; }\n\n")
	css.WriteString("      [owa] .mj-carousel-thumbnail { display: none !important; }\n")
	css.WriteString("      \n")
	css.WriteString("      @media screen yahoo {\n")
	css.WriteString(fmt.Sprintf("          .mj-carousel-%s-icons-cell,\n", carouselID))
	css.WriteString("          .mj-carousel-previous-icons,\n")
	css.WriteString("          .mj-carousel-next-icons {\n")
	css.WriteString("              display: none !important;\n")
	css.WriteString("          }\n\n")

	// One "+ *" per image after the first, as mjml-carousel's
	// repeat('+ *', length - 1).
	padding := " " + strings.Repeat("+ *", imageCount-1) + "+"
	css.WriteString(fmt.Sprintf(
		"          .mj-carousel-%s-radio-1:checked%s .mj-carousel-content .mj-carousel-%s-thumbnail-1 {\n",
		carouselID,
		padding,
		carouselID,
	))
	css.WriteString("              border-color: transparent;\n")
	css.WriteString("          }\n")
	css.WriteString("      }")

	return css.String()
}

// generateCarouselID generates a unique ID for the carousel
func (c *MJCarouselComponent) generateCarouselID() string {
	// newElementID never returns "", so an empty id means not generated yet.
	if c.id == "" {
		c.id = c.newElementID()
	}
	return c.id
}

// rendersChild reports whether Render writes child: an mj-carousel-image.
func (c *MJCarouselComponent) rendersChild(child Component) bool {
	_, ok := child.(*MJCarouselImageComponent)
	return ok
}

// getCarouselImages gets all mj-carousel-image children
func (c *MJCarouselComponent) getCarouselImages() []*MJCarouselImageComponent {
	var images []*MJCarouselImageComponent
	for _, child := range c.children {
		if c.rendersChild(child) {
			images = append(images, child.(*MJCarouselImageComponent))
		}
	}
	return images
}

// renderCarouselContent renders the main carousel HTML content
func (c *MJCarouselComponent) renderCarouselContent(w io.StringWriter, carouselID string, carouselImages []*MJCarouselImageComponent) error {
	leftIcon := c.resolveAttribute(c, constants.MJMLLeftIcon)
	rightIcon := c.resolveAttribute(c, constants.MJMLRightIcon)
	iconWidth := c.resolveAttribute(c, constants.MJMLIconWidth)
	thumbnails := c.resolveAttribute(c, constants.MJMLThumbnails)

	// Start MSO conditional comment
	if _, err := w.WriteString("<!--[if !mso]><!-->"); err != nil {
		return err
	}

	// Main carousel container
	if _, err := w.WriteString(`<div class="mj-carousel">`); err != nil {
		return err
	}

	// Render radio buttons for carousel state management
	if err := c.renderRadioButtons(w, carouselID, carouselImages); err != nil {
		return err
	}

	// Carousel content container
	if _, err := w.WriteString(`<div class="mj-carousel-content mj-carousel-`); err != nil {
		return err
	}
	if _, err := w.WriteString(carouselID); err != nil {
		return err
	}
	if _, err := w.WriteString(`-content" style="display:table;width:100%;table-layout:fixed;text-align:center;font-size:0px;">`); err != nil {
		return err
	}

	// The thumbnails, for visible and supported, as mjml-carousel's
	// renderThumbnails.
	if thumbnails == "visible" || thumbnails == "supported" {
		if err := c.renderThumbnails(w, carouselID, carouselImages, thumbnails); err != nil {
			return err
		}
	}

	// Main carousel table with images and navigation
	if err := c.renderCarouselTable(w, carouselID, carouselImages, leftIcon, rightIcon, iconWidth); err != nil {
		return err
	}

	// Close carousel content and main container
	if _, err := w.WriteString(`</div></div>`); err != nil {
		return err
	}

	// Close MSO conditional comment
	if _, err := w.WriteString("<!--<![endif]-->"); err != nil {
		return err
	}

	return nil
}

// renderMSOFallback renders the Outlook fallback, as mjml-carousel's
// renderFallback: nothing without children, else the first child, which is
// the first image only when no other tag comes before it (an unknown tag
// renders nothing, inside the conditional comment all the same).
func (c *MJCarouselComponent) renderMSOFallback(w io.StringWriter, carouselImages []*MJCarouselImageComponent) error {
	if c.childCount() == 0 {
		return nil
	}
	// MSO conditional comment for Outlook
	if _, err := w.WriteString("<!--[if mso]>"); err != nil {
		return err
	}

	if len(carouselImages) > 0 && imageNumber(carouselImages[0]) == 1 {
		if err := c.renderCarouselImageContent(w, carouselImages[0], 1, true); err != nil {
			return err
		}
	}

	if _, err := w.WriteString("<![endif]-->"); err != nil {
		return err
	}

	return nil
}

// renderRadioButtons renders the hidden radio buttons of the images, as
// mjml-carousel-image's renderRadio: numbered by their position among the
// carousel's children, the first checked only when it is the first child.
func (c *MJCarouselComponent) renderRadioButtons(w io.StringWriter, carouselID string, carouselImages []*MJCarouselImageComponent) error {
	for _, img := range carouselImages {
		i := imageNumber(img)
		checkedAttr := ""
		if i == 1 {
			checkedAttr = ` checked="checked"`
		}

		input := html.NewHTMLTag("input").
			AddAttribute(constants.AttrClass, fmt.Sprintf("mj-carousel-radio mj-carousel-%s-radio mj-carousel-%s-radio-%d", carouselID, carouselID, i))
		if checkedAttr != "" {
			input.AddAttribute("checked", "checked")
		}
		input.AddAttribute("type", "radio").
			AddAttribute("name", "mj-carousel-radio-"+carouselID).
			AddAttribute("id", fmt.Sprintf("mj-carousel-%s-radio-%d", carouselID, i)).
			AddAttribute(constants.AttrStyle, "display:none;mso-hide:all;")
		if err := input.RenderVoid(w); err != nil {
			return err
		}
	}
	return nil
}

// renderThumbnails renders thumbnail navigation images
func (c *MJCarouselComponent) renderThumbnails(w io.StringWriter, carouselID string, carouselImages []*MJCarouselImageComponent, thumbnails string) error {
	for _, img := range carouselImages {
		// A thumbnail is hidden when thumbnails is "supported", the image's
		// own value first, as mjml-carousel-image's hasThumbnailsSupported.
		display := "inline-block"
		imageThumbnails := img.resolveAttribute(img, constants.MJMLThumbnails)
		if imageThumbnails == "" {
			imageThumbnails = thumbnails
		}
		if imageThumbnails == "supported" {
			display = "none"
		}
		imageNum := imageNumber(img)
		// The image's own thumbnail attributes, else the carousel's, which it
		// passes down (childContext).
		tbBorder := img.resolveAttribute(img, constants.MJMLTBBorder)
		tbBorderRadius := img.resolveAttribute(img, constants.MJMLTBBorderRadius)
		tbWidth := img.resolveAttribute(img, constants.MJMLTBWidth)
		// Use thumbnails-src if available, otherwise fall back to src
		src := img.resolveAttribute(img, constants.MJMLThumbnailsSrc)
		if src == "" {
			src = img.resolveAttribute(img, constants.MJMLSrc)
		}
		href := fmt.Sprintf("#%d", imageNum)
		target := img.resolveAttribute(img, constants.MJMLTarget)

		// Build thumbnail CSS classes including any css-class from mj-carousel-image
		baseClasses := fmt.Sprintf("mj-carousel-thumbnail mj-carousel-%s-thumbnail mj-carousel-%s-thumbnail-%d", carouselID, carouselID, imageNum)
		imageClasses := img.resolveAttribute(img, constants.MJMLCSSClass)
		if imageClasses != "" {
			baseClasses += " " + suffixCSSClasses(imageClasses, "thumbnail")
		}

		// Thumbnail link
		link := html.NewHTMLTag("a").
			AddAttribute(constants.AttrStyle, "border:"+tbBorder+";border-radius:"+tbBorderRadius+";display:"+display+";overflow:hidden;width:"+tbWidth+";").
			AddAttribute(constants.AttrHref, href).
			AddAttribute("target", target).
			AddAttribute(constants.AttrClass, baseClasses)
		if err := link.RenderOpen(w); err != nil {
			return err
		}

		// Thumbnail label and image
		if _, err := w.WriteString(fmt.Sprintf(`<label for="mj-carousel-%s-radio-%d">`, carouselID, imageNum)); err != nil {
			return err
		}
		thumbnail := html.NewHTMLTag("img").
			AddAttribute(constants.AttrStyle, "display:block;width:100%;height:auto;").
			AddAttribute(constants.AttrSrc, src).
			AddAttribute(constants.AttrAlt, img.resolveAttribute(img, constants.MJMLAlt)).
			AddAttribute(constants.AttrWidth, parseIntAttribute(tbWidth))
		if err := thumbnail.RenderVoid(w); err != nil {
			return err
		}
		if _, err := w.WriteString("</label>"); err != nil {
			return err
		}

		if _, err := w.WriteString("</a>"); err != nil {
			return err
		}
	}
	return nil
}

// renderCarouselTable renders the main carousel table with images and navigation
func (c *MJCarouselComponent) renderCarouselTable(w io.StringWriter, carouselID string, carouselImages []*MJCarouselImageComponent, leftIcon, rightIcon, iconWidth string) error {
	// Main carousel table
	if _, err := w.WriteString(`<table border="0" cellpadding="0" cellspacing="0" role="presentation" width="100%" class="mj-carousel-main" style="caption-side:top;display:table-caption;table-layout:fixed;width:100%;"><tbody><tr>`); err != nil {
		return err
	}

	// Left navigation icons cell
	if _, err := w.WriteString(fmt.Sprintf(`<td class="mj-carousel-%s-icons-cell" style="font-size:0px;display:none;mso-hide:all;padding:0px;">`, carouselID)); err != nil {
		return err
	}

	if err := c.renderPreviousIcons(w, carouselID, c.childCount(), leftIcon); err != nil {
		return err
	}

	if _, err := w.WriteString("</td>"); err != nil {
		return err
	}

	// Main images cell
	if _, err := w.WriteString(`<td style="padding:0px;"><div class="mj-carousel-images">`); err != nil {
		return err
	}

	// Render all carousel images
	for _, img := range carouselImages {
		if err := c.renderCarouselImageContent(w, img, imageNumber(img), false); err != nil {
			return err
		}
	}

	if _, err := w.WriteString("</div></td>"); err != nil {
		return err
	}

	// Right navigation icons cell
	if _, err := w.WriteString(fmt.Sprintf(`<td class="mj-carousel-%s-icons-cell" style="font-size:0px;display:none;mso-hide:all;padding:0px;">`, carouselID)); err != nil {
		return err
	}

	if err := c.renderNextIcons(w, carouselID, c.childCount(), rightIcon); err != nil {
		return err
	}

	if _, err := w.WriteString("</td>"); err != nil {
		return err
	}

	// Close table
	if _, err := w.WriteString("</tr></tbody></table>"); err != nil {
		return err
	}

	return nil
}

// renderPreviousIcons renders the previous navigation icons
func (c *MJCarouselComponent) renderPreviousIcons(w io.StringWriter, carouselID string, imageCount int, leftIcon string) error {
	if _, err := w.WriteString(`<div class="mj-carousel-previous-icons" style="display:none;mso-hide:all;">`); err != nil {
		return err
	}

	iconWidth := c.resolveAttribute(c, constants.MJMLIconWidth)

	// The width attribute is parseInt(icon-width), as mjml-carousel writes it.
	iconWidthValue := parseIntAttribute(iconWidth)
	for i := 1; i <= imageCount; i++ {
		if _, err := w.WriteString(fmt.Sprintf(`<label for="mj-carousel-%s-radio-%d" class="mj-carousel-previous mj-carousel-previous-%d">`, carouselID, i, i)); err != nil {
			return err
		}
		icon := html.NewHTMLTag("img").
			AddAttribute(constants.AttrSrc, leftIcon).
			AddAttribute(constants.AttrAlt, "previous").
			AddAttribute(constants.AttrStyle, "display:block;width:"+iconWidth+";height:auto;").
			AddAttribute(constants.AttrWidth, iconWidthValue)
		if err := icon.RenderVoid(w); err != nil {
			return err
		}
		if _, err := w.WriteString("</label>"); err != nil {
			return err
		}
	}

	if _, err := w.WriteString("</div>"); err != nil {
		return err
	}
	return nil
}

// renderNextIcons renders the next navigation icons
func (c *MJCarouselComponent) renderNextIcons(w io.StringWriter, carouselID string, imageCount int, rightIcon string) error {
	if _, err := w.WriteString(`<div class="mj-carousel-next-icons" style="display:none;mso-hide:all;">`); err != nil {
		return err
	}

	iconWidth := c.resolveAttribute(c, constants.MJMLIconWidth)

	// The width attribute is parseInt(icon-width), as mjml-carousel writes it.
	iconWidthValue := parseIntAttribute(iconWidth)
	for i := 1; i <= imageCount; i++ {
		if _, err := w.WriteString(fmt.Sprintf(`<label for="mj-carousel-%s-radio-%d" class="mj-carousel-next mj-carousel-next-%d">`, carouselID, i, i)); err != nil {
			return err
		}
		icon := html.NewHTMLTag("img").
			AddAttribute(constants.AttrSrc, rightIcon).
			AddAttribute(constants.AttrAlt, "next").
			AddAttribute(constants.AttrStyle, "display:block;width:"+iconWidth+";height:auto;").
			AddAttribute(constants.AttrWidth, iconWidthValue)
		if err := icon.RenderVoid(w); err != nil {
			return err
		}
		if _, err := w.WriteString("</label>"); err != nil {
			return err
		}
	}

	if _, err := w.WriteString("</div>"); err != nil {
		return err
	}
	return nil
}

// renderCarouselImageContent renders a single carousel image
func (c *MJCarouselComponent) renderCarouselImageContent(w io.StringWriter, img *MJCarouselImageComponent, imageNum int, isFallback bool) error {
	// As mjml-carousel-image: the style takes the container width as written,
	// with its fraction, the width attribute its parseInt.
	return renderCarouselImage(w, img, imageNum, isFallback, jsPixels(c.layoutWidth()), c.GetEffectiveWidth())
}

// renderCarouselImage writes the div and image of mjml-carousel-image's
// render: the image numbered imageNum, hidden after the first one, at the
// container width widthPx (width attribute widthAttr); isFallback for the
// Outlook fallback image. The border radius is written when it is set, as
// mjml-core leaves out undefined styles: inside a carousel, which passes it,
// always.
func renderCarouselImage(w io.StringWriter, img *MJCarouselImageComponent, imageNum int, isFallback bool, widthPx string, widthAttr int) error {
	src := img.resolveAttribute(img, constants.MJMLSrc)
	borderRadius, borderRadiusSet := attributeOf(img, constants.MJMLBorderRadius)
	alt := img.resolveAttribute(img, constants.MJMLAlt)
	title := img.resolveAttribute(img, constants.MJMLTitle)
	href := img.resolveAttribute(img, constants.MJMLHref)

	// Build CSS classes for the container div
	containerClasses := fmt.Sprintf("mj-carousel-image mj-carousel-image-%d", imageNum)
	imageClasses := img.resolveAttribute(img, constants.MJMLCSSClass)
	if imageClasses != "" {
		containerClasses += " " + imageClasses
	} else if isFallback {
		containerClasses += " "
	}
	div := html.NewHTMLTag("div").AddAttribute(constants.AttrClass, containerClasses)
	if isFallback {
		div.AddAttribute(constants.AttrStyle, "")
	} else {
		if imageNum > 1 {
			div.AddStyle(constants.CSSDisplay, constants.DisplayNone).AddStyle(constants.CSSMSOHide, "all")
		}
		// The mj-style inline rules for its classes; juice does not
		// reach the Outlook fallback, inside a conditional comment.
	}
	var open strings.Builder
	if err := div.RenderOpen(&open); err != nil {
		return err
	}
	divOpen := open.String()
	if isFallback {
		// The Outlook fallback, which the minifier does not see, keeps
		// MJML's space before the >.
		divOpen = strings.TrimSuffix(divOpen, ">") + " >"
	}
	if _, err := w.WriteString(divOpen); err != nil {
		return err
	}

	// The link around the image when there is an href, with its rel as
	// set, even empty.
	if href != "" {
		link := html.NewHTMLTag("a").AddAttribute(constants.AttrHref, href)
		img.addSetAttribute(img, link, constants.MJMLRel)
		link.AddAttribute(constants.AttrTarget, constants.TargetBlank)
		if err := link.RenderOpen(w); err != nil {
			return err
		}
	}

	// title as set; an empty one only in the Outlook fallback, which the
	// minifier does not see.
	image := html.NewHTMLTag("img")
	if title != "" || (isFallback && img.hasAttribute(img, constants.MJMLTitle)) {
		image.AddAttribute(constants.AttrTitle, title)
	}
	style := ""
	if borderRadiusSet {
		style = "border-radius:" + borderRadius + ";"
	}
	image.AddAttribute(constants.AttrSrc, src).
		AddAttribute(constants.AttrAlt, alt).
		AddAttribute(constants.AttrStyle, style+"display:block;width:"+widthPx+";max-width:100%;height:auto;").
		AddAttribute(constants.AttrWidth, strconv.Itoa(widthAttr)).
		AddAttribute(constants.AttrBorder, "0")
	render := image.RenderVoid
	if isFallback {
		render = image.RenderSelfClosing
	}
	if err := render(w); err != nil {
		return err
	}

	// Close link wrapper if href was present
	if href != "" {
		if _, err := w.WriteString("</a>"); err != nil {
			return err
		}
	}

	_, err := w.WriteString("</div>")
	return err
}

// carouselPassedAttributes are the attributes mj-carousel passes down to its
// images, as its renderChildren calls do: the border radius of the images and
// the thumbnail border, border radius and width. An image's own value wins.
var carouselPassedAttributes = map[string]struct{}{
	constants.MJMLBorderRadius:   {},
	constants.MJMLTBBorder:       {},
	constants.MJMLTBBorderRadius: {},
}

// childContext passes the carousel's image and thumbnail attributes down to
// its images, with tb-width as mjml-carousel's thumbnailsWidth: the carousel's
// tb-width, or 110px without one (its context has no parentWidth, so the
// share of the parent width it would compare with is NaN).
func (c *MJCarouselComponent) childContext(ctx ChildContext) ChildContext {
	ctx.PassedAttributes = c.passedAttributes(c, carouselPassedAttributes)
	tbWidth := c.resolveAttribute(c, constants.MJMLTBWidth)
	if tbWidth == "" {
		tbWidth = "110px"
	}
	ctx.PassedAttributes["tb-width"] = tbWidth
	return ctx
}
